"""Director V25 TXT owns visuals/audio/captions/transitions, not selected UI preset."""
import ast
from pathlib import Path
import sys
import tempfile
import unittest

ROOT = Path(__file__).resolve().parents[1]
WEB = ROOT / "apps/scene-builder/part01"
WORKER = ROOT / "apps/scene-builder/part02"
sys.path.insert(0, str(WEB))
sys.path.insert(0, str(WORKER))

from director_v25 import preflight_v25
from director_v25_execution import compile_v25
from director_v25_transitions import DirectorTransitionError, resolve_director_transitions
from test_scene_director_v25_execution import Catalog, plan, CAPS


class DirectorSoleAuthorityTests(unittest.TestCase):
    def test_music_true_is_blocked_not_silently_selected_from_preset(self):
        with tempfile.TemporaryDirectory() as tmp:
            catalog = Catalog(Path(tmp), ["Alexa 6.mp4"])
            txt = plan().replace("music_enabled=false", "music_enabled=true")
            result = preflight_v25(txt, catalog.list(), "library_only", True, CAPS)
            self.assertEqual(result["status"], "BLOCKED")
            self.assertIn("explicit track-binding", " ".join(result["errors"]))

    def test_captions_and_lut_values_come_from_txt(self):
        with tempfile.TemporaryDirectory() as tmp:
            catalog = Catalog(Path(tmp), ["Alexa 6.mp4"])
            txt = plan()
            txt = txt.replace("caption_position=bottom", """caption_position=bottom
font=dejavu_sans_bold
text_color=#f5f5f5
highlight_color=#ffcc00
outline_color=#101010
background_color=#111111
background_opacity_percent=34
font_size=38
max_words=4""")
            txt = txt.replace("lut_preset=filmic", "lut_preset=filmic\nlut_strength_percent=65")
            cap = {**CAPS, "caption_fonts": ["dejavu_sans_bold"]}
            result = compile_v25(
                txt, catalog, source_mode="library_only", library_enabled=True,
                selected_preset="cinematic_documentary", capabilities=cap,
            )
            settings = result["settings"]
            self.assertEqual(settings["lut_strength_percent"], 65)
            self.assertFalse(settings["lut_normalize_enabled"])
            self.assertFalse(settings["lut_scene_aware_enabled"])
            self.assertFalse(settings["lut_continuity_enabled"])
            self.assertEqual(settings["caption_text_color"], "#f5f5f5")
            self.assertEqual(settings["caption_highlight_color"], "#ffcc00")
            self.assertEqual(settings["caption_font_size"], 38)
            self.assertEqual(settings["caption_font"], "dejavu_sans_bold")
            self.assertEqual(settings["caption_max_words"], 4)
            self.assertEqual(settings["video_quality_preset"], "original")
            for effect in ("sfx_enabled", "environment_sfx_enabled",
                           "transition_sfx_library_enabled", "capcut_noise_enabled",
                           "capcut_mirror_enabled"):
                self.assertFalse(settings[effect], effect)
            self.assertEqual(result["sections"]["AUDIO"]["music_enabled"], "false")

    def test_transition_details_are_exact_not_autogenerated(self):
        rows = [
            {"director_v25_shot":"SCENE_001.SHOT_01", "transition_out":"cross_dissolve",
             "transition_duration_ms":250, "duration":1.4},
            {"director_v25_shot":"SCENE_002.SHOT_01", "transition_out":"hard_cut",
             "transition_duration_ms":0, "duration":1.0},
        ]
        result, report = resolve_director_transitions(rows)
        self.assertEqual(result[0]["transition_out"], "cross_dissolve")
        self.assertEqual(result[0]["transition_duration_ms"], 250)
        self.assertEqual(result[0]["transition_engine"], "xfade")
        self.assertFalse(result[0]["transition_auto"])
        self.assertFalse(report["preset_used"])
        self.assertEqual(result[1]["transition_engine"], "cut")
        self.assertEqual(result[1]["transition_sfx"], "none")
        self.assertEqual(rows[0]["transition_out"], "cross_dissolve")

    def test_unrenderable_transition_fails_not_silently_clamps(self):
        rows = [
            {"director_v25_shot":"SCENE_001.SHOT_01", "transition_out":"cross_dissolve",
             "transition_duration_ms":600, "duration":.30},
            {"director_v25_shot":"SCENE_002.SHOT_01", "transition_out":"none",
             "transition_duration_ms":0, "duration":1},
        ]
        with self.assertRaisesRegex(DirectorTransitionError, "exceeds adjacent"):
            resolve_director_transitions(rows)

    def test_classic_auto_engine_still_available_and_director_is_opt_in(self):
        web = (WEB / "app.py").read_text(encoding="utf-8")
        worker = (WORKER / "api_server.py").read_text(encoding="utf-8")
        ast.parse(web)
        ast.parse(worker)
        ast.parse((WORKER/"director_v25_transitions.py").read_text(encoding="utf-8"))
        self.assertIn("if director_compilation is not None:", web)
        self.assertIn('"director_v25_narration_original"', web)
        self.assertIn("director_txt", web)
        self.assertIn("resolve_director_transitions(", worker)
        self.assertIn("assign_auto_transitions(", worker)
        self.assertIn('"director_txt": "sole_creative_source"', worker)


if __name__ == "__main__":
    unittest.main()
